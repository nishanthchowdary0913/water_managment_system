CREATE DATABASE IF NOT EXISTS water_management
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE water_management;

CREATE TABLE IF NOT EXISTS admin (
  id INT UNSIGNED NOT AUTO_INCREMENT,
  username VARCHAR(100) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS residents (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  full_name VARCHAR(100) NOT NULL,
  phone VARCHAR(10) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS water_facilities (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  facility_name VARCHAR(150) NOT NULL,
  facility_type VARCHAR(100) NOT NULL,
  location VARCHAR(150) NOT NULL,
  status VARCHAR(50) NOT NULL,
  description TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS water_availability (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  area VARCHAR(150) NOT NULL,
  supply_status ENUM('Available', 'Limited', 'Not Available') NOT NULL,
  supply_time VARCHAR(100) NOT NULL,
  remarks TEXT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS complaints (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  resident_name VARCHAR(100) NOT NULL,
  phone VARCHAR(10) NOT NULL,
  area VARCHAR(150) NOT NULL,
  complaint_type VARCHAR(100) NOT NULL,
  description TEXT NOT NULL,
  status ENUM('Pending', 'In Progress', 'Resolved') NOT NULL DEFAULT 'Pending',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
) ENGINE=InnoDB;
